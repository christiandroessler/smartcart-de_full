DROP TABLE IF EXISTS saved_carts;
DROP TABLE IF EXISTS shopping_list;
DROP TABLE IF EXISTS user_settings;
DROP TABLE IF EXISTS store_prices;
DROP TABLE IF EXISTS products;

CREATE TABLE products (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  category TEXT NOT NULL,
  unit TEXT NOT NULL,
  base_unit TEXT NOT NULL,
  base_factor REAL NOT NULL,
  is_gluten_free INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE store_prices (
  product_id TEXT NOT NULL,
  store TEXT NOT NULL,
  price REAL,
  promo INTEGER DEFAULT 0,
  promo_label TEXT,
  external_id TEXT,
  brand_name TEXT,
  search_query TEXT,
  updated_at TEXT DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (product_id, store),
  FOREIGN KEY (product_id) REFERENCES products(id)
);

CREATE TABLE user_settings (
  user_key TEXT PRIMARY KEY,
  plz TEXT NOT NULL DEFAULT '37308',
  strategy TEXT NOT NULL DEFAULT 'split',
  updated_at TEXT DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE shopping_list (
  user_key TEXT NOT NULL,
  product_id TEXT NOT NULL,
  qty INTEGER NOT NULL DEFAULT 1,
  PRIMARY KEY (user_key, product_id),
  FOREIGN KEY (product_id) REFERENCES products(id)
);

CREATE TABLE saved_carts (
  id TEXT PRIMARY KEY,
  user_key TEXT NOT NULL,
  name TEXT NOT NULL,
  items_json TEXT NOT NULL,
  created_at TEXT DEFAULT CURRENT_TIMESTAMP
);

